import assert from 'node:assert/strict';
import {execFileSync} from 'node:child_process';
import {mkdtemp,readFile,rm} from 'node:fs/promises';
import {tmpdir} from 'node:os';
import {join} from 'node:path';
import {ensureBrowser} from '@remotion/renderer';
import {chromium} from 'playwright-core';

const scratch=await mkdtemp(join(tmpdir(),'remain-effects-'));
let browser;
try {
  const runtime=await ensureBrowser();
  browser=await chromium.launch({executablePath:runtime.path,args:['--no-sandbox']});
  const page=await browser.newPage({viewport:{width:1440,height:900},acceptDownloads:true});
  const errors=[];
  page.on('pageerror',error=>errors.push(error.message));
  await page.goto(process.env.STUDIO_TEST_URL ?? 'http://127.0.0.1:4317');
  const openTab = name => page.getByRole('tab',{name,exact:true}).click();
  await openTab('Hiệu ứng');
  const effects=page.getByRole('region',{name:'Hiệu ứng chữ'});
  const preset=effects.getByLabel('Preset chữ');
  const scope=effects.getByLabel('Phạm vi hiệu ứng');
  const slider=page.getByRole('slider',{name:'Vị trí timeline'});
  const lyrics=page.locator('[data-lyric-preset]');
  const overlay=page.locator('[data-song-section]');
  await slider.fill('45');
  assert.equal(await lyrics.getAttribute('data-lyric-preset'),'classic');
  await preset.selectOption('aurora');
  await scope.selectOption('line');
  await preset.selectOption('classic');
  await effects.getByLabel('Font chữ').selectOption('mono');
  await openTab('Canh từ');
  await page.locator('.words button').first().click();
  await openTab('Hiệu ứng');
  await effects.getByRole('button',{name:'Nhấn từ: Một'}).click();
  assert.equal(await lyrics.locator('[data-word-emphasis]').textContent(),'Một');
  await scope.selectOption('project');
  await effects.getByLabel('Font chữ').selectOption('sans');
  assert.equal(await lyrics.getAttribute('data-lyric-preset'),'classic');
  assert.match(await lyrics.evaluate(el=>el.style.fontFamily),/Courier/);
  await effects.getByLabel('Hiện thanh Verse/Chorus trong video').check();
  await slider.fill('0');
  await effects.getByRole('button',{name:'Thêm đoạn tại playhead'}).click();
  assert.equal(await overlay.getAttribute('data-song-section'),'verse');
  await slider.fill('150');
  await effects.getByLabel('Loại đoạn').selectOption('chorus');
  await effects.getByRole('button',{name:'Thêm đoạn tại playhead'}).click();
  await effects.getByRole('button',{name:'Verse · 0.00s'}).click();
  assert.equal(await overlay.getAttribute('data-song-section'),'verse');
  await effects.getByRole('button',{name:'Chorus · 5.00s'}).click();
  assert.equal(await overlay.getAttribute('data-song-section'),'chorus');
  assert.equal(await lyrics.getAttribute('data-lyric-preset'),'aurora');
  const progress=overlay.locator('[data-section-progress]');
  async function sampleFrame(frame) {
    await slider.fill(String(frame));
    return progress.evaluate(el=>({scale:Number(el.dataset.sectionProgress),style:el.style.backgroundColor}),undefined,{timeout:1500});
  }
  const before=await sampleFrame(149);
  const boundary=await sampleFrame(150);
  const after=await sampleFrame(158);
  assert.ok(before.scale<boundary.scale && boundary.scale<after.scale,'Progress should not reset at a section boundary');
  assert.equal(before.style,boundary.style,'The track color must not jump at the section boundary');
  assert.notEqual(after.style,boundary.style,'The track color should ease into the new palette');
  assert.deepEqual(await sampleFrame(150),boundary,'Seeking backward should recreate the exact same progress and color');
  const outgoing=page.locator('[data-outgoing-lyric]');
  await outgoing.getByText('Một',{exact:true}).waitFor();
  const exitStart=await outgoing.evaluate(el=>({opacity:Number(el.style.opacity),transform:el.style.transform}));
  assert.equal(exitStart.opacity,1);
  await sampleFrame(158);
  assert.ok(await outgoing.evaluate(el=>Number(el.style.opacity)<1 && Number(el.style.opacity)>0));
  await sampleFrame(185);
  await outgoing.waitFor({state:'detached'});
  await effects.getByLabel('Hiện thanh Verse/Chorus trong video').uncheck();
  await overlay.waitFor({state:'detached'});
  await effects.getByLabel('Hiện thanh Verse/Chorus trong video').check();
  await openTab('Project');
  const saved=page.waitForEvent('download');
  await page.getByRole('button',{name:'Lưu project'}).click();
  const path=join(scratch,'project.json');
  await (await saved).saveAs(path);
  const project=JSON.parse(await readFile(path,'utf8'));
  assert.deepEqual(project.sections,[{start:0,kind:'verse'},{start:5,kind:'chorus'}]);
  assert.equal(project.cues[0].effect.font,'mono');
  assert.equal(project.cues[0].words[0].emphasis,true);
  assert.equal(project.effect.font,'sans');
  await openTab('Hiệu ứng');
  await preset.selectOption('classic');
  await openTab('Project');
  await page.locator('#project-file').setInputFiles(path);
  await page.getByText('Đã nạp project.json').waitFor();
  await openTab('Hiệu ứng');
  await effects.getByRole('button',{name:'Chorus · 5.00s'}).click();
  assert.equal(await lyrics.getAttribute('data-lyric-preset'),'aurora');
  await page.setViewportSize({width:320,height:840});
  assert.ok(await page.evaluate(()=>document.documentElement.scrollWidth<=window.innerWidth));
  if (!process.env.STUDIO_PREVIEW_ONLY) {
    await page.getByLabel('Phạm vi xuất').selectOption('range');
    await page.getByLabel('Bắt đầu (giây)').fill('4.5');
    await page.getByLabel('Kết thúc (giây)').fill('6');
    const exported=page.waitForEvent('download',{timeout:90000});
    await page.getByRole('button',{name:'Xuất MP4',exact:true}).click();
    const mp4=process.env.STUDIO_EFFECTS_MP4 ?? join(scratch,'chorus.mp4');
    await (await exported).saveAs(mp4);
    const probe=JSON.parse(execFileSync('ffprobe',['-v','error','-select_streams','v:0','-show_entries','stream=codec_name,nb_frames','-of','json',mp4],{encoding:'utf8'}));
    assert.deepEqual(probe.streams.map(({codec_name,nb_frames})=>({codec_name,nb_frames})),[{codec_name:'h264',nb_frames:'45'}]);
    const crop=(t,region)=>execFileSync('ffmpeg',['-v','error','-ss',t,'-i',mp4,'-vf',`crop=${region},format=rgb24`,'-frames:v','1','-f','rawvideo','-']);
    // Sample the same point in the top rail before and after the boundary.
    const cool=crop('0.3','2:2:100:0');
    const warm=crop('1.3','2:2:100:0');
    assert.ok(cool[2]>cool[0] && warm[0]>warm[2],`Expected cooler Verse and warmer Chorus rail: ${[...cool.subarray(0,3)]} -> ${[...warm.subarray(0,3)]}`);
    const label=crop('1.3','240:32:20:12');
    assert.ok(label.some((r,i)=>i%3===0 && r>140 && label[i+1]>140 && label[i+2]>140),'Expected section label pixels in the exported header');
  }
  assert.deepEqual(errors,[]);
  console.log('Verified presets, line override, word emphasis, section seek/toggle, project reload and mobile layout'+(process.env.STUDIO_PREVIEW_ONLY?'.':', plus rendered section overlay.'));
} finally {
  await browser?.close();
  await rm(scratch,{recursive:true,force:true});
}
