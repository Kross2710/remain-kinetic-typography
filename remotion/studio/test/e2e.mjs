import assert from 'node:assert/strict';
import {mkdtemp,readFile,rm} from 'node:fs/promises';
import {tmpdir} from 'node:os';
import {join} from 'node:path';
import {execFileSync,spawnSync} from 'node:child_process';
import {chromium} from 'playwright-core';
import {ensureBrowser} from '@remotion/renderer';

const base = process.env.STUDIO_TEST_URL ?? 'http://127.0.0.1:4317';
const browserStatus = await ensureBrowser();
assert.ok('path' in browserStatus, JSON.stringify(browserStatus));
const dir = await mkdtemp(join(tmpdir(),'remain-e2e-'));
let browser;
try {
  const audio = join(dir,'own-audio.mp3');
  const output = process.env.STUDIO_TEST_OUTPUT ?? join(dir,'export.mp4');
  execFileSync('ffmpeg',['-v','error','-f','lavfi','-i','sine=frequency=440:duration=30','-y',audio]);
  browser = await chromium.launch({executablePath: browserStatus.path,args:['--no-sandbox']});
  const page = await browser.newPage({viewport:{width:1440,height:900},acceptDownloads:true});
  const errors=[];
  page.on('pageerror',e=>errors.push(e.message));
  await page.goto(base);
  await page.getByRole('heading',{name:'Remain Studio'}).waitFor();
  const openTab = name => page.getByRole('tab',{name,exact:true}).click();
  await openTab('Media');
  await page.locator('#audio-file').setInputFiles(audio);
  await page.locator('.filename').getByText('own-audio.mp3',{exact:true}).waitFor();
  await openTab('Lời');
  await page.locator('#lyrics').fill('[00:00.00]Một hai ba bốn\n[00:03.00]Chữ chuyển động\n[00:25.00]Hẹn gặp lại');
  await page.getByRole('button',{name:'Áp dụng lời'}).click();
  await openTab('Canh từ');
  const slider=page.getByRole('slider',{name:'Vị trí timeline'});
  const syncTabPanel=page.getByRole('tabpanel',{name:'Canh từ'});
  async function seek(seconds) {
    await slider.fill(String(seconds*30));
    await page.waitForFunction(s=>Math.abs(Number(document.querySelector('#timeline').value) - s*30)<=1,seconds);
  }
  await page.getByRole('button',{name:'hai',exact:false}).filter({has:page.locator('small')}).click();
  await seek(.7);
  await syncTabPanel.focus();
  await page.keyboard.press('t');
  await page.getByRole('button',{name:'hai 0.70s'}).waitFor({timeout:3000});
  await seek(4);
  await page.locator('[data-word-active="true"]').getByText('Chữ',{exact:true}).waitFor();
  await seek(1);
  await page.locator('[data-word-active="true"]').getByText('hai',{exact:true}).waitFor();
  await page.getByRole('button',{name:'Phát',exact:true}).click();
  const tapPanel=page.locator('.panel').filter({has:page.getByRole('heading',{name:'Canh từng từ',exact:true})});
  assert.equal(await tapPanel.evaluate(el=>el===document.activeElement),true,'Clicking Play should hand focus to the lyric timing panel');
  await page.keyboard.down('Space');
  await page.getByRole('button',{name:/^bốn /,pressed:true}).waitFor({timeout:3000});
  await page.keyboard.up('Space');
  await page.keyboard.press('t');
  await page.getByRole('button',{name:/^Chữ /,pressed:true}).waitFor({timeout:3000});
  await page.waitForFunction(()=>Number(document.querySelector('#timeline').value)>40);
  await page.getByRole('button',{name:'Tạm dừng',exact:true}).click();
  const shorter = join(dir,'short-track.mp3');
  execFileSync('ffmpeg',['-v','error','-f','lavfi','-i','sine=frequency=330:duration=2','-y',shorter]);
  await openTab('Media');
  await page.locator('#audio-file').setInputFiles(shorter);
  await page.locator('.filename').getByText('short-track.mp3',{exact:true}).waitFor();
  assert.equal(await page.locator('#cue-picker option').count(),3);
  assert.equal(await page.locator('.track button').count(),1);
  await openTab('Canh từ');
  await page.getByRole('button',{name:'hai 0.70s'}).waitFor();
  await openTab('Media');
  await page.locator('#audio-file').setInputFiles(audio);
  await page.locator('.filename').getByText('own-audio.mp3',{exact:true}).waitFor();
  assert.equal(await page.locator('.track button').count(),3);
  await openTab('Canh từ');
  await page.getByRole('button',{name:'hai 0.70s'}).waitFor();
  // The next word was estimated at 10.33s; marking the first at 12s should still work.
  await page.locator('#cue-picker').selectOption('1');
  await seek(12);
  await page.getByRole('button',{name:'Đóng dấu từ'}).click();
  await page.getByRole('button',{name:'Chữ 12.00s'}).waitFor({timeout:3000});
  await page.locator('#cue-picker').selectOption('0');
  await seek(2.6);
  await page.getByRole('button',{name:/^bốn /}).click();
  await page.keyboard.press('t');
  await page.getByRole('button',{name:'Chữ 12.00s',pressed:true}).waitFor({timeout:3000});
  // The focused last-word button was removed by switching to a shorter line.
  assert.equal(await page.evaluate(()=>document.activeElement.tagName),'BODY');
  await page.getByRole('button',{name:'Phát',exact:true}).evaluate(button=>button.click());
  await page.waitForFunction(()=>Number(document.querySelector('#timeline').value)>=96);
  await page.keyboard.press('Space');
  await page.getByRole('button',{name:/^chuyển /,pressed:true}).waitFor({timeout:3000});
  const nextLineStart = await page.getByLabel('Mốc đầu dòng (giây)').inputValue();
  assert.ok(Number(nextLineStart)>=3.2 && Number(nextLineStart)<12,'Tap must retime the next line without waiting for its estimated start');
  await page.getByRole('button',{name:'Tạm dừng',exact:true}).click();
  const lyrics = page.locator('#lyrics');
  await openTab('Lời');
  const oldLyrics = await lyrics.inputValue();
  await lyrics.focus();
  await lyrics.evaluate(el=>el.setSelectionRange(el.value.length,el.value.length));
  await page.keyboard.press('t');
  assert.equal(await lyrics.inputValue(),oldLyrics+'t');
  await openTab('Canh từ');
  await page.getByRole('button',{name:/^chuyển /,pressed:true}).waitFor({timeout:3000});
  const linePicker = page.locator('#cue-picker');
  await linePicker.selectOption('2');
  await syncTabPanel.focus();
  await page.keyboard.press('t');
  await page.getByRole('button',{name:/^gặp /,pressed:true}).waitFor({timeout:3000});
  await seek(25.4);
  await syncTabPanel.focus();
  await page.keyboard.press('t');
  await page.getByRole('button',{name:/^lại /,pressed:true}).waitFor({timeout:3000});
  await seek(26);
  await syncTabPanel.focus();
  await page.keyboard.press('t');
  await tapPanel.getByText('Đã tới cuối lời', {exact:true}).waitFor({timeout:3000});
  const lastWord=tapPanel.getByRole('button',{name:/^lại /});
  const finalStamp=await lastWord.innerText();
  await seek(27);
  await syncTabPanel.focus();
  await page.keyboard.press('t');
  assert.equal(await lastWord.innerText(),finalStamp);

  // Cue history: Ctrl+Z / Ctrl+Shift+Z walk the word stamps.
  const undoButton = page.getByRole('button', {name: 'Hoàn tác', exact: true});
  const redoButton = page.getByRole('button', {name: 'Làm lại', exact: true});
  assert.equal(await undoButton.isEnabled(), true, 'A tapped word must be undoable');
  assert.equal(await redoButton.isEnabled(), false, 'Nothing has been undone yet');
  const stampedWord = tapPanel.getByRole('button', {name: /^lại /});
  const stampedText = await stampedWord.innerText();
  await openTab('Lời');
  await lyrics.focus();
  await page.keyboard.press('Control+z');
  await openTab('Canh từ');
  assert.equal(await stampedWord.innerText(), stampedText, 'Ctrl+Z typed in the lyrics field stays a text undo');
  await page.getByRole('button', {name: 'Vừa khung'}).focus();
  await page.keyboard.press('Control+z');
  assert.notEqual(await stampedWord.innerText(), stampedText, 'Ctrl+Z must roll the last word stamp back');
  assert.equal(await redoButton.isEnabled(), true);
  await page.keyboard.press('Control+Shift+z');
  assert.equal(await stampedWord.innerText(), stampedText, 'Ctrl+Shift+Z must bring the stamp back');

  // Timeline zoom: the cue blocks are placed by time * pxPerSec, so the scale
  // has to show up in their measured width, and Fit must find the original.
  const cueBlock = page.locator('.track button').first();
  const fitted = (await cueBlock.boundingBox()).width;
  await page.getByRole('button', {name: 'Phóng to timeline'}).click();
  assert.ok((await cueBlock.boundingBox()).width > fitted * 1.3, 'Zooming in must widen the cue blocks');
  await page.getByRole('button', {name: 'Thu nhỏ timeline'}).click();
  assert.ok(Math.abs((await cueBlock.boundingBox()).width - fitted) <= 1, 'Zooming back out must restore the scale');
  await page.getByRole('button', {name: 'Vừa khung'}).click();
  assert.ok(Math.abs((await cueBlock.boundingBox()).width - fitted) <= 1, 'Fit must restore the timeline scale');

  // Project file: save the editing session, wipe it, load it back.
  const savedPath = join(dir, 'project.json');
  await openTab('Project');
  const projectDownload = page.waitForEvent('download', {timeout: 15000});
  await page.getByRole('button', {name: 'Lưu project', exact: true}).click();
  await (await projectDownload).saveAs(savedPath);
  const saved = JSON.parse(await readFile(savedPath, 'utf8'));
  assert.deepEqual([saved.version, saved.cues.length, saved.width, saved.height], [1, 3, 720, 1280]);
  assert.ok(saved.cues[0].words.some(w => w.confirmed), 'A saved project must keep the locked word marks');
  await openTab('Lời');
  await lyrics.fill('[00:00.00]Một dòng mới');
  await page.getByRole('button', {name: 'Áp dụng lời'}).click();
  assert.equal(await page.locator('.track button').count(), 1);
  await openTab('Project');
  await page.locator('#project-file').setInputFiles(savedPath);
  await page.getByText('Đã nạp project.json').waitFor({timeout: 5000});
  assert.equal(await page.locator('.track button').count(), 3);
  await openTab('Canh từ');
  await page.getByRole('button', {name: 'hai 0.70s'}).waitFor({timeout: 3000});
  await openTab('Lời');
  assert.match(await lyrics.inputValue(), /^\[00:00\.00\]/, 'A loaded project must refill the lyrics editor');
  await openTab('Canh từ');

  if (process.env.STUDIO_SCREENSHOT) await page.screenshot({path:process.env.STUDIO_SCREENSHOT});
  if (!process.env.STUDIO_PREVIEW_ONLY) {
    const download = page.waitForEvent('download',{timeout:240_000});
    const response = page.waitForResponse(r=>new URL(r.url()).pathname==='/api/render' && r.request().method()==='POST',{timeout:240_000});
    await page.getByRole('button',{name:'Xuất MP4',exact:true}).click();
    const result = await response;
    if(!result.ok()) throw Error(`Export HTTP ${result.status()}: ${await result.text()}`);
    await (await download).saveAs(output);
    const meta=JSON.parse(execFileSync('ffprobe',['-v','error','-show_streams','-show_format','-of','json',output],{encoding:'utf8'}));
    const video=meta.streams.find(s=>s.codec_type==='video');
    assert.deepEqual([video.codec_name,video.width,video.height,video.r_frame_rate,video.nb_frames],['h264',720,1280,'30/1','900']);
    assert.ok(meta.streams.some(s=>s.codec_type==='audio' && s.codec_name==='aac'));
    assert.ok(Math.abs(Number(meta.format.duration)-30)<.1);
    const meter = spawnSync('ffmpeg',['-hide_banner','-i',output,'-map','0:a:0','-af','volumedetect','-f','null','-'],{encoding:'utf8'});
    assert.equal(meter.status,0,meter.stderr);
    assert.ok(Number(meter.stderr.match(/max_volume:\s*(-?[\d.]+) dB/)?.[1])>-50,'Expected uploaded audio, not a silent stream');
    const hashAt = t => execFileSync('ffmpeg',['-v','error','-ss',String(t),'-i',output,'-map','0:v:0','-frames:v','1','-f','md5','-'],{encoding:'utf8'}).trim();
    assert.notEqual(hashAt(1),hashAt(4));
    console.log('MP4 download verified: 900 H.264 frames, AAC, 30s.');
  }
  assert.deepEqual(errors,[]);
  await page.setViewportSize({width:390,height:844});
  assert.ok(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth));
  console.log('Browser upload, lyric import, tap, playback, backward seek and mobile width verified.');
} finally {
  await browser?.close();
  await rm(dir,{recursive:true,force:true});
}